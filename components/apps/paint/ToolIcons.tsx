/** One rectangle per horizontal run of a colour, so an icon is a handful of elements. */
function runs(map: string[]) {
    const out: { x: number; y: number; w: number; fill: string }[] = [];
    map.forEach((row, y) => {
        let x = 0;
        while (x < row.length) {
            const ch = row[x];
            const fill = INK[ch];
            if (!fill) {
                x++;
                continue;
            }
            let end = x + 1;
            while (end < row.length && row[end] === ch) end++;
            out.push({ x, y, w: end - x, fill });
            x = end;
        }
    });
    return out;
}

const RUNS = Object.fromEntries(Object.entries(MAPS).map(([id, map]) => [id, runs(map)])) as Record<ToolId, ReturnType<typeof runs>>;

export const ToolIcon = memo(function ToolIcon({ tool }: { tool: ToolId }) {
    return (
        <svg width="16" height="16" viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden>
            {RUNS[tool].map((r, i) => (
                <rect key={i} x={r.x} y={r.y} width={r.w} height={1} fill={r.fill} />
            ))}
        </svg>
    );
});
